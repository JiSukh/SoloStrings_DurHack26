"""Golden vectors shared by the Python and C++ tests: tests/bar_vectors.json.

Each vector is one pattern + chord at one tempo: the bar string encode_bar() makes, and the
plucks simulate() says the sequencer plays over two bars ([frame, strings], frame = 20 ms).
tests/python/test_music.py checks Python still produces them; tests/cpp/sequencer_test.cpp
checks sequencer.h parses each bar and plays exactly the same frames.

Regenerate after a deliberate change to patterns or timing:
    python3 tests/python/bar_vectors.py
"""

import json
from pathlib import Path

import _path  # noqa: F401
from strummer.music import PATTERNS, SUB_PER_TICK, encode_bar, parse_bar, simulate

FILE = Path(__file__).resolve().parents[1] / "bar_vectors.json"
CHORDS = [None, "C", "D"]  # every string; a low-A root; a chord that mutes both low strings
TEMPOS = [60, 90, 200]


def build():
    vectors = []
    for name, pattern in PATTERNS.items():
        for chord in CHORDS:
            bar = encode_bar(pattern, chord)
            length, _ = parse_bar(bar)
            for bpm in TEMPOS:
                frames = -(-2 * length * SUB_PER_TICK // bpm) + 2  # two bars and a bit
                vectors.append({"pattern": name, "chord": chord or "", "bpm": bpm, "frames": frames,
                                "bar": bar, "plucks": simulate(bar, bpm, frames)})
    return {"about": "generated by tests/python/bar_vectors.py; see there", "vectors": vectors}


def dumps(data):
    # one vector per line keeps diffs readable
    lines = ",\n".join("  " + json.dumps(v, separators=(",", ":")) for v in data["vectors"])
    return '{"about":' + json.dumps(data["about"]) + ',"vectors":[\n' + lines + "\n]}\n"


if __name__ == "__main__":
    FILE.write_text(dumps(build()))
    print(f"wrote {FILE}")
